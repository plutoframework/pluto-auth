func TestCommentSpacing(t *testing.T) {
	cases := []struct {
		name  string
		input string
		count int
	}{
		{"file header", "// Header.\npackage p\n", 0},
		{
			"statement",
			"package p\nfunc f() {\n x := 1\n // Explain.\n // Continue.\n _ = x\n}\n",
			1,
		},
		{"block start", "package p\nfunc f() {\n // Explain.\n}\n", 1},
		{
			"block comment",
			"package p\n/* Explain.\n Continue. */\nfunc f() {}\n",
			1,
		},
		{"inline", "package p\nvar x = 1 // Explain.\n", 0},
		{"separated", "package p\n\n// Explain.\nvar x = 1\n", 0},
		{"raw string", "package p\nvar x = `text\n// Not a comment.\n`\n", 0},
		{"directive", "package p\n//go:noinline\nfunc f() {}\n", 0},
		{
			"line directive",
			"package p\n//line other.go:99\n// Explain.\nvar x = 1\n",
			0,
		},
		{
			"generated",
			"// Code generated by tool. DO NOT EDIT.\npackage p\n// Explain.\nvar x = 1\n",
			0,
		},
		{"cgo", "package p\n/* #include <stdlib.h> */\nimport \"C\"\n", 1},
		{"crlf", "package p\r\n// Explain.\r\nvar x = 1\r\n", 1},
	}
	for _, test := range cases {
		t.Run(test.name, func(t *testing.T) {
			input := []byte(test.input)

			lines, err := missing(input)
			if err != nil || len(lines) != test.count {
				t.Fatalf(
					"missing = %v, %v; want %d findings",
					lines,
					err,
					test.count,
				)
			}

			fixed := format(input, lines)

			again, err := missing(fixed)
			if err != nil || len(again) != 0 {
				t.Fatalf("fix is not accepted: %v, %v", again, err)
			}

			if !bytes.Equal(format(fixed, again), fixed) {
				t.Fatal("fix is not idempotent")
			}

			if test.count == 0 && !bytes.Equal(input, fixed) {
				t.Fatal("changed accepted input")
			}
		})
	}
}

func TestRepositoryCheckAndFix(t *testing.T) {
	root := t.TempDir()
	path := filepath.Join(root, "example.go")

	input := "package p\nfunc f() {\n x := 1\n // Explain.\n _ = x\n}\n"
	if err := os.WriteFile(path, []byte(input), 0o600); err != nil {
		t.Fatal(err)
	}

	if err := run(root, false, ""); err == nil {
		t.Fatal("check accepted missing comment spacing")
	}

	unchanged, err := os.ReadFile(path)
	if err != nil || string(unchanged) != input {
		t.Fatalf("check modified input: %v", err)
	}

	if err := run(root, true, ""); err != nil {
		t.Fatal(err)
	}

	fixed, err := os.ReadFile(path)
	if err != nil ||
		!strings.Contains(string(fixed), "x := 1\n\n // Explain.\n _ = x") {
		t.Fatalf("fix did not preserve comment attachment: %s, %v", fixed, err)
	}

	if err := run(root, false, ""); err != nil {
		t.Fatal(err)
	}
}
